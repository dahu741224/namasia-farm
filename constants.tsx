export const parseProducts = (): Product[] => {
  return RAW_PRODUCTS.split('\n')
    .filter(line => line.trim() !== '')
    .map(line => {
      const [id, category, subCategory, name, isSeasonal, isVeg, canFreeze, price, note, weight, imageUrl] = line.split(',');
      return {
        id, category, subCategory, name,
        isSeasonal: isSeasonal === 'Y',
        isVeg: isVeg === '全素',
        canFreeze: canFreeze === 'Y',
        price: parseInt(price),
        note, weight: parseInt(weight),
        imageUrl: imageUrl?.trim() || undefined
      };
    });
};

export const parseMealKits = (): MealKit[] => {
  return RAW_MEAL_KITS.split('\n')
    .filter(line => line.trim() !== '')
    .map((line, idx) => {
      const [tag, portion, name, meat, veggie, sauce, time, steps, price] = line.split(',');
      return {
        id: `mk-${idx}`,
        tag: `#${tag}`,
        portion, name, meat, veggie, sauce, time, steps,
        price: parseInt(price)
      };
    });
};

